export function getTotalLessons(): number {
  return UNITS.reduce((sum, u) => sum + u.lessons.length, 0);
}

export function getAllVocab() {
  return UNITS.flatMap(u =>
    u.lessons.flatMap(l =>
      l.vocab.map(v => ({ ...v, unitId: u.id, unitTitle: u.title, lessonId: l.id }))
    )
  );
}
